// scripts/generate-redirects.mjs
// Generates the root _redirects file from real archived data.
//
// Why this exists: the previous site was a static Astro build that served
// /go/<slug> as its canonical entry URL. The current TanStack app serves the
// same content at /listings/<slug>. Search Console still holds ~10k /go/ URLs
// in "Discovered - currently not indexed" and reports /vs/, /best, /support
// and /category/ as 404, which holds up AdSense review.
//
// All 101 archived slugs are still live under /listings/, so the /go/ map is
// a lossless 1:1 redirect rather than a catch-all.
//
// Run: node scripts/generate-redirects.mjs
// Wired into package.json so `npm run build` always refreshes it.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

// --- Inputs -----------------------------------------------------------------

// Every slug the archived Astro build published. All are still live.
const archivedSlugs = readdirSync(resolve(ROOT, "data", "listings"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""));

const archivedCategories = JSON.parse(
  readFileSync(resolve(ROOT, "data", "categories.json"), "utf8"),
).map((c) => c.slug);

// Pages the current app serves, used for trailing-slash normalisation.
const livePages = [
  "/", "/about", "/changelog", "/contact", "/insights",
  "/methodology", "/privacy", "/terms",
];

const retiredPages = [
  ["/support", "/contact"],
  ["/best", "/"],
  ["/sponsor", "/"],
  ["/home", "/"],
  ["/rss.xml", "/sitemap.xml"],
];

// --- Output -----------------------------------------------------------------

const lines = [
  "# Cloudflare Pages redirects - generated by scripts/generate-redirects.mjs",
  "# Do not edit by hand; edit the generator and re-run it.",
  "#",
  "# Cloudflare Pages applies the first matching rule, so the lossless",
  "# /go/ -> /listings/ map is listed before the catch-alls.",
  "",];

const push = (from, to) => lines.push(`${from.padEnd(32)} ${to.padEnd(22)} 301`);

// 1. Lossless map: every archived entry URL keeps its original destination.
//    All 101 slugs are still published at /listings/<slug>.
lines.push("# --- /go/<slug> -> /listings/<slug> (all 101 slugs still published) ---");
for (const slug of archivedSlugs.sort()) push(`/go/${slug}`, `/listings/${slug}`);

// 2. Comparison pages ("a-vs-b"). No comparison route exists on the current
//    site; the directory index is the closest equivalent.
lines.push("", "# --- Archived comparison pages ---");
push("/vs/*", "/");

// 3. Categories were filter states on the old homepage, never standalone pages.
lines.push("", "# --- Archived categories (filters now live on the homepage) ---");
for (const slug of archivedCategories.sort()) push(`/category/${slug}`, "/");

// 4. Retired top-level pages.
lines.push("", "# --- Retired top-level pages ---");
for (const [from, to] of retiredPages) push(from, to);

// 5. Trailing-slash normalisation. TanStack Start answers /page/ with a 307,
//    which Google treats as a temporary move. A 301 is the correct signal.
lines.push("", "# --- Trailing slash -> canonical (framework default is a 307) ---");
for (const page of livePages) {
  if (page === "/") continue;
  push(`${page}/`, page);
}
push("/listings/*/", "/listings/*");

lines.push("", "");

const out = resolve(ROOT, "_redirects");
writeFileSync(out, lines.join("\n"), "utf8");

const count = lines.filter((l) => l.trim().endsWith("301")).length;
console.log(
  `OK: wrote ${count} redirect rules to ${out}\n` +
  `    ${archivedSlugs.length} lossless /go/ entries, ` +
  `${archivedCategories.length} categories, ${livePages.length - 1} trailing-slash fixes`,
);